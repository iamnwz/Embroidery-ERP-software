-- Keep records in the order they were entered (the app lists some things in entry order).
do $$
declare t text;
begin
  foreach t in array array['customers','suppliers','machines','employees','items','orders','payments',
                           'purchases','stock','supplier_payments','production','salaries','expenses']
  loop
    execute format('alter table public.%I add column if not exists pos bigint generated by default as identity', t);
    execute format('create index if not exists %I on public.%I (pos)', t || '_pos_idx', t);
  end loop;
end $$;
